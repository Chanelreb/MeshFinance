/* Live Calendly inline booking, prefilled with the visitor's name/email.
   Mounts only when step 3 renders, so the widget initialises on demand. */
const FFC_CALENDLY_URL = "https://calendly.com/chanel-fqxz/intro_to_mesh?hide_event_type_details=1&hide_gdpr_banner=1&text_color=102a43&primary_color=3898e0";
function CalendlyEmbed({ prefill, onScheduled }) {
  const ref = React.useRef(null);
  React.useEffect(() => {
    const el = ref.current;
    const init = () => {
      if (window.Calendly && el && !el.hasChildNodes()) {
        window.Calendly.initInlineWidget({ url: FFC_CALENDLY_URL, parentElement: el, prefill: prefill || {} });
      }
    };
    if (window.Calendly) { init(); return; }
    let sc = document.getElementById("calendly-widget-js");
    if (!sc) {
      sc = document.createElement("script");
      sc.id = "calendly-widget-js";
      sc.src = "https://assets.calendly.com/assets/external/widget.js";
      sc.async = true;
      document.head.appendChild(sc);
    }
    sc.addEventListener("load", init);
    return () => sc.removeEventListener("load", init);
  }, []);
  /* Calendly posts a message when a booking is confirmed — redirect then. */
  React.useEffect(() => {
    const handler = (e) => {
      if (e.data && typeof e.data === "object" && e.data.event === "calendly.event_scheduled") {
        onScheduled && onScheduled();
      }
    };
    window.addEventListener("message", handler);
    return () => window.removeEventListener("message", handler);
  }, [onScheduled]);
  return <div ref={ref} style={{ minWidth: 260, height: 700 }} aria-label="Book a time with Mesh Finance"/>;
}

/* Industry-body logo. Shows the image if it loads, otherwise a labelled
   placeholder badge until the real logo file is added to assets. */
function AssocLogo({ src, label }) {
  const [failed, setFailed] = React.useState(false);
  if (failed) return <span style={s.logoBadge} aria-label={label}>{label}</span>;
  return <img src={src} alt={label} style={s.logoImg} onError={()=>setFailed(true)}/>;
}

/* Google reviews (Trustindex) widget — same loader used on the homepage. */
function GoogleReviews() {
  const ref = React.useRef(null);
  React.useEffect(() => {
    const el = ref.current;
    if (!el || el.hasChildNodes()) return;
    const sc = document.createElement("script");
    sc.src = "https://cdn.trustindex.io/loader.js?1f3f74d765942510b78680b7215";
    sc.async = true;
    sc.defer = true;
    el.appendChild(sc);
  }, []);
  return <div ref={ref} aria-label="Google reviews for Mesh Finance"/>;
}

